/** Explicit opt-in: this makes two real native subscription requests with only
 * synthetic data. Run OMS_CLAUDE_LIVE=1 node --test test/claude-code-live.test.ts. */
test(
  'native Claude Code returns a real Pi tool result through guarded execution',
  { skip: process.env.OMS_CLAUDE_LIVE !== '1', timeout: 120_000 },
  async () => {
    const directory = mkdtempSync(join(tmpdir(), 'oms-native-roundtrip-'));
    const cwd = join(directory, 'project');
    mkdirSync(cwd);
    const agentDir = join(directory, 'agent');
    const nonce = randomUUID();
    let executed = 0,
      guarded = 0;
    let session: AgentSession | undefined;
    let native: ClaudeCodeSession | undefined;
    try {
      const runtime = await ModelRuntime.create({
        credentials: new InMemoryCredentialStore(),
        modelsPath: null,
        refreshOnCreate: false,
      });
      native = await createClaudeCodeProvider(runtime);
      await runtime.refresh({ allowNetwork: false });
      const settingsManager = createHarnessSettings(agentDir);
      const loader = new DefaultResourceLoader({
        cwd,
        agentDir,
        settingsManager,
        noExtensions: true,
        noSkills: true,
        noContextFiles: true,
        noPromptTemplates: true,
        noThemes: true,
        appendSystemPrompt: [],
        systemPrompt:
          'Call nonce_probe exactly once, then return the nonce from the actual tool result. A deferred execution placeholder is never a nonce. If the actual tool result appears in conversation history, do not call tools again; return that nonce.',
        extensionFactories: [
          (pi) => {
            pi.on('tool_call', () => {
              guarded++;
            });
            pi.on('session_before_compact', () => ({ cancel: true }));
            pi.registerTool({
              name: 'nonce_probe',
              label: 'Nonce probe',
              description: 'Return a random test nonce generated by the harness. No file or network access.',
              parameters: Type.Object({}),
              async execute() {
                executed++;
                return { content: [{ type: 'text', text: nonce }], details: undefined };
              },
            });
          },
        ],
      });
      await loader.reload();
      const model = runtime.getModel('claude-code', 'haiku');
      assert.ok(model);
      ({ session } = await createAgentSession({
        cwd,
        agentDir,
        modelRuntime: runtime,
        model,
        settingsManager,
        resourceLoader: loader,
        sessionManager: SessionManager.inMemory(cwd),
        noTools: 'builtin',
        tools: ['nonce_probe'],
      }));
      await session.bindExtensions({});
      await session.prompt('Call nonce_probe once, then return the nonce from its real result.');
      const final = session.messages.findLast((message) => message.role === 'assistant');
      assert.ok(final?.role === 'assistant');
      assert.equal(final.stopReason, 'stop');
      const text = final.content
        .filter((block) => block.type === 'text')
        .map((block) => block.text)
        .join('');
      assert.ok(
        text.includes(nonce),
        'the final native response includes the actual tool result, which was absent from the user prompt',
      );
      assert.equal(executed, 1);
      assert.equal(guarded, 1);
      assert.equal(session.messages.filter((message) => message.role === 'assistant').length, 2);
      const identity = native.status().sessionId;
      await session.prompt('Return the nonce from your previous answer without calling any tools.');
      const followup = session.messages.findLast((message) => message.role === 'assistant');
      assert.ok(followup?.role === 'assistant');
      assert.equal(followup.stopReason, 'stop');
      assert.ok(JSON.stringify(followup.content).includes(nonce));
      assert.equal(executed, 1);
      assert.equal(native.status().sessionId, identity);
      await native.disconnect();
      await session.prompt('After reconnecting, return that same previously observed nonce without calling tools.');
      const resumed = session.messages.findLast((message) => message.role === 'assistant');
      assert.ok(resumed?.role === 'assistant');
      assert.equal(resumed.stopReason, 'stop');
      assert.ok(JSON.stringify(resumed.content).includes(nonce));
      assert.equal(executed, 1);
      assert.equal(native.status().sessionId, identity);
    } finally {
      session?.dispose();
      await native?.close();
      rmSync(directory, { recursive: true, force: true });
    }
  },
);

/** Requires a real local Surfpool binary and the host sandbox. The fixture is
 * synthetic; no user project files are sent to the provider. */
test(
  'native Claude Code completes a real OMS task through its independent verifier',
  {
    skip: process.env.OMS_CLAUDE_LIVE_FULL !== '1',
    timeout: 120_000,
  },
  async () => {
    const binary = process.env.SURFPOOL_BINARY;
    assert.ok(binary, 'SURFPOOL_BINARY must identify the trusted installed Surfpool executable');
    const fixture = await createHarnessFixture(defaultHarnessEnvironment(binary, 'host'));
    let harness: HarnessSession | undefined;
    try {
      harness = await createHarnessSession({
        ...fixture.options,
        modelRuntime: fixture.modelRuntime,
        modelSelection: { provider: 'claude-code', id: 'haiku' },
        caps: { tokens: 2_000_000, spendMicroUsd: 1_000_000, wallClockMs: 120_000 },
        maxOutputTokens: 1024,
        executionMode: 'bounded',
        hostApprovalPolicy: 'allow',
        endRunOnProposal: true,
      });
      const completed: string[] = [];
      harness.session.subscribe((event) => {
        if (event.type === 'tool_execution_end' && !event.isError) completed.push(event.toolName);
      });
      await harness.session.prompt(
        'This is an isolated connector smoke test. The active requirement is fixture. Use write to set amount.mjs to exactly export const amount = 10; then call propose_done for item fixture. Do not edit verify.mjs. Only the independent verifier can close the requirement.',
      );
      const state = harness.evaluator.read();
      assert.ok(state.ok);
      assert.equal(
        state.value.items[0]?.status,
        'closed',
        JSON.stringify(
          harness.session.messages
            .filter((message) => message.role === 'assistant')
            .map((message) => ({
              stopReason: message.stopReason,
              error: message.errorMessage,
              content: message.content,
            })),
        ),
      );
      assert.ok(completed.includes('write'));
      assert.ok(completed.includes('propose_done'));
      assert.equal(harness.budget.snapshot().used.spendMicroUsd, 0);
      assert.equal(harness.budget.snapshot().accounting, 'known');
      assert.deepEqual(harness.budget.snapshot().pendingDispatchIds, []);
    } finally {
      await harness?.close();
      rmSync(fixture.base, { recursive: true, force: true });
    }
  },
);

/** Synthetic text only: reset must not import the old OMS display history. */
test(
  'native reset changes identity and cannot recall the previous synthetic secret',
  { skip: process.env.OMS_CLAUDE_LIVE !== '1', timeout: 120_000 },
  async () => {
    const runtime = await ModelRuntime.create({
      credentials: new InMemoryCredentialStore(),
      modelsPath: null,
      refreshOnCreate: false,
    });
    const native = await createClaudeCodeProvider(runtime);
    await runtime.refresh({ allowNetwork: false });
    const model = runtime.getModel('claude-code', 'haiku');
    assert.ok(model);
    const secret = randomUUID();
    const transcript = normalizeContext({
      systemPrompt:
        'Answer questions directly; if a previous secret is absent from this conversation, reply UNKNOWN and never guess.',
      tools: [],
      messages: [{ role: 'user', content: `Remember the secret ${secret} and reply ACK.`, timestamp: 1 }],
    });
    try {
      const first = await native.stream(model, transcript).result();
      assert.equal(first.stopReason, 'stop');
      const oldId = native.status().sessionId;
      await native.reset();
      assert.notEqual(native.status().sessionId, oldId);
      transcript.messages.push(first, {
        role: 'user',
        content: 'What secret did I previously give you? Reply UNKNOWN if it is absent.',
        timestamp: 2,
      });
      const fresh = await native.stream(model, transcript).result();
      assert.equal(fresh.stopReason, 'stop');
      assert.ok(!JSON.stringify(fresh.content).includes(secret));
      assert.match(JSON.stringify(fresh.content), /UNKNOWN/);
    } finally {
      await native.close();
    }
  },
);
